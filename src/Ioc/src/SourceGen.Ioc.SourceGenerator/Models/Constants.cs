    public const string IocRegisterDefaultsAttributeFullName_T1 = "SourceGen.Ioc.IocRegisterDefaultsAttribute`1";
    public const string IocImportModuleAttributeFullName = "SourceGen.Ioc.IocImportModuleAttribute";
    public const string IocImportModuleAttributeFullName_T1 = "SourceGen.Ioc.IocImportModuleAttribute`1";
    public const string IocDiscoverAttributeFullName = "SourceGen.Ioc.IocDiscoverAttribute";
    public const string IocDiscoverAttributeFullName_T1 = "SourceGen.Ioc.IocDiscoverAttribute`1";
    public const string IocInjectAttributeFullName = "SourceGen.Ioc.IocInjectAttribute";
    public const string IocGenericFactoryAttributeFullName = "SourceGen.Ioc.IocGenericFactoryAttribute";
    public const string IocContainerAttributeFullName = "SourceGen.Ioc.IocContainerAttribute";

    /// <summary>
    /// The MSBuild property name for the root namespace.
    /// </summary>
    public const string RootNamespaceProperty = "build_property.RootNamespace";

    /// <summary>
    /// The MSBuild property name for customizing the generated method name.
    /// </summary>
    /// <remarks>
    /// Usage in .csproj:
    /// <code>
    /// &lt;PropertyGroup&gt;
    ///     &lt;SourceGenIocName&gt;CustomName&lt;/SourceGenIocName&gt;
    /// &lt;/PropertyGroup&gt;
    /// &lt;ItemGroup&gt;
    ///     &lt;CompilerVisibleProperty Include="SourceGenIocName" /&gt;
    /// &lt;/ItemGroup&gt;
    /// </code>
    /// </remarks>
    public const string SourceGenIocNameProperty = "build_property.SourceGenIocName";

    /// <summary>
    /// The MSBuild property name for configuring the default service lifetime.
    /// </summary>
    /// <remarks>
    /// Usage in .csproj:
    /// <code>
    /// &lt;PropertyGroup&gt;
    ///     &lt;SourceGenIocDefaultLifetime&gt;Scoped&lt;/SourceGenIocDefaultLifetime&gt;
    /// &lt;/PropertyGroup&gt;
    /// </code>
    /// Valid values: Singleton, Scoped, Transient (case-insensitive). Defaults to Transient.
    /// </remarks>
    public const string SourceGenIocDefaultLifetimeProperty = "build_property.SourceGenIocDefaultLifetime";

    /// <summary>
    /// The MSBuild property name for configuring enabled IoC generation features.
    /// </summary>
    public const string SourceGenIocFeaturesProperty = "build_property.SourceGenIocFeatures";

    public const string Category_Usage = "Usage";
    public const string Category_Design = "Design";

    // Generated code constants
    public const string AutoGeneratedHeader = "// <auto-generated/>";

    /// <summary>
    /// Nullable context of generated files: annotations keep the nullability of generated signatures, while disabled
    /// warnings skip nullable flow analysis, which dominated the compiler's binding time of large generated files.
    /// Tests compile generated files with <c>#nullable enable</c> to keep checking them for nullable warnings.
    /// </summary>
    public const string NullableAnnotations = "#nullable enable annotations";
    public const string NullableWarningsDisabled = "#nullable disable warnings";

    /// <summary>
    /// <c>[GeneratedCode]</c> with this generator's version, for generated types.
    /// </summary>
    public static readonly string GeneratedCodeAttribute =
        $"[global::System.CodeDom.Compiler.GeneratedCode(\"SourceGen.Ioc\", \"{GetGeneratorVersion()}\")]";

    /// <summary>
    /// Gets the generator's file version without its fourth component, the git height that nbgv increments
    /// with every commit, so generated code changes only when the version in <c>version.json</c> changes.
    /// </summary>
    private static string? GetGeneratorVersion() =>
        typeof(Constants).Assembly.GetCustomAttribute<AssemblyFileVersionAttribute>()?.Version is { } fileVersion
            && Version.TryParse(fileVersion, out var version)
            ? version.ToString(3)
            : null;

    public const string IServiceProviderTypeName = "System.IServiceProvider";
    public const string IServiceProviderGlobalTypeName = "global::System.IServiceProvider";
    public const string KeyedServiceAnyKey = "global::Microsoft.Extensions.DependencyInjection.KeyedService.AnyKey";

    /// <summary>
    /// File-level alias for a container resolver entry, <c>KeyValuePair&lt;ServiceIdentifier, Func&lt;TContainer, object&gt;&gt;</c>.
    /// Explicitly typed entries bind much faster than target-typed <c>new(...)</c> in large nullable-enabled array initializers.
    /// </summary>
    public const string ResolverEntryAlias = "__IocResolver";

    // Service provider method names
    public const string GetRequiredService = "GetRequiredService";
    public const string GetService = "GetService";
    public const string GetRequiredKeyedService = "GetRequiredKeyedService";
    public const string GetKeyedService = "GetKeyedService";
    public const string GetServices = "GetServices";
    public const string GetKeyedServices = "GetKeyedServices";

    extension(ServiceLifetime lifetime)
    {
        public string Name =>
            lifetime switch
            {
                ServiceLifetime.Singleton => "Singleton",
                ServiceLifetime.Scoped => "Scoped",
                ServiceLifetime.Transient => "Transient",
                _ => lifetime.ToString()
            };
    }
}
