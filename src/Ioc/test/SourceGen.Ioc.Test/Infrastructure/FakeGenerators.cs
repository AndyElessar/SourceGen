using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

// The fake descriptors are test data, not rules of a shipped analyzer
#pragma warning disable RS2008

namespace SourceGen.Ioc.Test.Infrastructure;

/// <summary>
/// A small generator that follows the rules of the real one. The tests of the helpers use it, so that the helpers are
/// checked before the real generator has features.
/// <list type="bullet">
/// <item>A class named <c>FakePartial…</c> gets a generated partial declaration and a generated helper type.</item>
/// <item>A class named <c>FakeWarn</c>, <c>FakeError</c>, or <c>FakeInfo</c> gets the related diagnostic on its name.</item>
/// <item>A class named <c>FakeTwice</c> gets the warning two times on its name.</item>
/// <item>The step <see cref="EmptyStep"/> never has an output.</item>
/// </list>
/// </summary>
internal sealed class FakeGenerator : IIncrementalGenerator
{
    public const string ModelStep = "FakeModels";
    public const string EmptyStep = "FakeEmpty";

    public static readonly DiagnosticDescriptor Warning = new("FAKE001", "Fake warning", "Warning on '{0}'", "Fake", DiagnosticSeverity.Warning, true);
    public static readonly DiagnosticDescriptor Error = new("FAKE002", "Fake error", "Error on '{0}'", "Fake", DiagnosticSeverity.Error, true, customTags: WellKnownDiagnosticTags.NotConfigurable);
    public static readonly DiagnosticDescriptor Info = new("FAKE003", "Fake info", "Info on '{0}'", "Fake", DiagnosticSeverity.Info, true);

    /// <summary>The model keeps only the file path and the span of the name, never a location.</summary>
    private readonly record struct FakeModel(string Name, string FilePath, int Start, int Length);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<FakeModel> models = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax c && c.Identifier.Text.StartsWith("Fake", StringComparison.Ordinal),
                static (ctx, _) => ((ClassDeclarationSyntax)ctx.Node) is var c
                    ? new FakeModel(c.Identifier.Text, c.SyntaxTree.FilePath, c.Identifier.Span.Start, c.Identifier.Span.Length)
                    : default)
            .WithTrackingName(ModelStep);

        context.RegisterSourceOutput(models.Where(static _ => false).WithTrackingName(EmptyStep), static (_, _) => { });

        context.RegisterSourceOutput(models.Where(static m => m.Name.StartsWith("FakePartial", StringComparison.Ordinal)), static (spc, model) => spc.AddSource($"{model.Name}.g.cs", $$"""
            // <auto-generated/>
            #nullable enable annotations
            #nullable disable warnings
            #pragma warning disable SGIOCEXP001

            partial class {{model.Name}}
            {
                [global::System.CodeDom.Compiler.GeneratedCode("SourceGen.Ioc", "1.2.3")]
                public int Generated() => {{model.Name}}_Helper.Value;
            }

            [global::System.CodeDom.Compiler.GeneratedCode("SourceGen.Ioc", "1.2.3")]
            internal static class {{model.Name}}_Helper
            {
                public static int Value => 1;
            }
            """));

        // The diagnostic pipeline: combine with the compilation, find the tree by its path, and create the location on it
        IncrementalValueProvider<(ImmutableArray<FakeModel> Left, Compilation Right)> diagnostics = models
            .Where(static m => m.Name is "FakeWarn" or "FakeError" or "FakeInfo" or "FakeTwice")
            .Collect()
            .Combine(context.CompilationProvider);

        context.RegisterSourceOutput(diagnostics, static (spc, input) =>
        {
            foreach(FakeModel model in input.Left)
            {
                SyntaxTree tree = input.Right.SyntaxTrees.Single(t => t.FilePath == model.FilePath);
                DiagnosticDescriptor descriptor = model.Name switch
                {
                    "FakeWarn" or "FakeTwice" => Warning,
                    "FakeError" => Error,
                    _ => Info,
                };
                Location location = Location.Create(tree, new TextSpan(model.Start, model.Length));
                spc.ReportDiagnostic(Diagnostic.Create(descriptor, location, model.Name));
                if(model.Name == "FakeTwice")
                {
                    spc.ReportDiagnostic(Diagnostic.Create(descriptor, location, model.Name));
                }
            }
        });
    }
}

/// <summary>A generator that breaks the cache: it puts a symbol into a pipeline step.</summary>
internal sealed class LeakyGenerator : IIncrementalGenerator
{
    public const string Step = "Leaky";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<ISymbol?> symbols = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, _) => ctx.SemanticModel.GetDeclaredSymbol(ctx.Node))
            .WithTrackingName(Step);

        context.RegisterSourceOutput(symbols, static (_, _) => { });
    }
}


/// <summary>A generator that throws. The driver reports this only as the warning CS8785.</summary>
internal sealed class ThrowingGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
        => context.RegisterSourceOutput(context.CompilationProvider, static (_, _) => throw new InvalidOperationException("boom"));
}

/// <summary>A generator whose model holds an array, which compares by reference and breaks the cache.</summary>
internal sealed class ArrayModelGenerator : IIncrementalGenerator
{
    public const string Step = "ArrayModel";

    private sealed record ArrayModel(string Name, int[] Values);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<ArrayModel> models = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, _) => new ArrayModel(((ClassDeclarationSyntax)ctx.Node).Identifier.Text, [1, 2]))
            .WithTrackingName(Step);

        context.RegisterSourceOutput(models, static (_, _) => { });
    }
}